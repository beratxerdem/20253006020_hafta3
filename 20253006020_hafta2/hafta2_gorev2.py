pi = 3.14159

yaricap = float(input("Lütfen silinidirin yarıçapını giriniz."))
yukseklik = float(input("Lütfen silinidirin yüksekligini giriniz."))

tabanAlani = pi * yaricap * yaricap

hacim = tabanAlani * yukseklik

print("Yaricap: ",yaricap)
print("Yükseklik: ", yukseklik)
print("Taban Alanı: ", tabanAlani)
print("Hacim: ", hacim)
